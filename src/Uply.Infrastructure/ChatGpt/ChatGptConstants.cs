namespace Uply.Infrastructure.ChatGpt;

public class ChatGptConstants
{
    public const string PromptTemplate = @"
Составь roadmap для достижения цели.

Начальное состояние: {StartingPoint}.
Конечная цель: {Goal}.
Дедлайн: {Deadline}.
Периодичность отчётов: {Period}.
Средняя сложность задачи (человеко-часы): {ManHoursPerTask}.

Формат ответа: JSON-массив из {TaskAmount} объектов.
Каждый объект имеет поля:
- ""title"": краткое название задачи (без номера шага).
- ""description"": конкретные инструкции, что именно нужно сделать, и указание, какой отчёт нужно предоставить для подтверждения выполнения.

Все задачи должны быть написаны на русском языке.

⚡ Очень важно:
- Все задачи должны быть напрямую связаны с тематикой конечной цели ({Goal}).
- Не добавляй задачи, которые выходят за рамки цели.
- Задачи должны быть абсолютно конкретными и измеримыми.
- Для спорта всегда указывай числа: например, ""пройти 10 000 шагов"", ""сделать 3 подхода по 12 приседаний"", ""съесть рацион на 2000 ккал"".
- Для изучения языков и других навыков — пошагово и конкретно: ""выучить 20 новых слов"", ""прочитать одну статью и выписать 10 выражений"".
- Не добавляй абстрактных задач вроде ""ознакомиться"", ""создать план"", ""обсудить"". Каждая задача должна быть проверяемой и требовать отчёта.
- Каждая задача должна быть выполнима за указанное количество человеко-часов ({ManHoursPerTask}).
- В description всегда указывай форму отчёта: код, текстовый файл, фото, скриншот, аудио или видео — в зависимости от тематики цели.
- Учитывай дедлайн и периодичность: количество задач должно соответствовать сроку и частоте отчётов.
- Постепенно увеличивай сложность и глубину задач, чтобы был виден прогресс.
- Добавляй разнообразие внутри тематики цели: разные аспекты, практику, теорию, анализ, мотивацию.
- При необходимости включай задачи на восстановление или поддержку (например, контроль стресса, дневник прогресса), но только если они напрямую помогают достичь цели.

Пример:
[
  {{
    ""title"": ""Практика базовых концепций"",
    ""description"": ""Изучи 3 ключевых концепции, относящиеся к цели ({Goal}). Подготовь краткий конспект и отправь текстовый файл.""
  }},
  {{
    ""title"": ""Применение на практике"",
    ""description"": ""Реализуй небольшой проект или упражнение, связанное с целью ({Goal}). Отправь исходники или фото результата.""
  }},
  {{
    ""title"": ""Контроль прогресса"",
    ""description"": ""Составь отчёт о достигнутых результатах за неделю, приложи фото/скриншоты/файлы подтверждения.""
  }}
]

Не добавляй пояснений, комментариев или текста вне JSON.
";



}
